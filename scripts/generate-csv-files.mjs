// Regenerates src/lib/data/csvFiles.ts from the CSV files in public/.
//
// Workers builds have no filesystem, so the CSV lists are inlined into the
// server bundle instead of being read with node:fs. Re-run this script after
// editing public/majors.csv, public/schools.csv or public/countries.csv:
//
//   pnpm gen:csv
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const files = [
    ['majors', 'MAJORS_CSV'],
    ['schools', 'SCHOOLS_CSV'],
    ['countries', 'COUNTRIES_CSV'],
];

function toTemplateLiteral(text) {
    return text
        .replaceAll('\\', '\\\\')
        .replaceAll('`', '\\`')
        .replaceAll('${', '\\${');
}

const entries = files.map(([name, constant]) => {
    const text = readFileSync(
        path.join(process.cwd(), 'public', `${name}.csv`),
        'utf-8'
    );
    return `export const ${constant} = \`${toTemplateLiteral(text)}\`;`;
});

const output = `// Generated by scripts/generate-csv-files.mjs — do not edit by hand.
// Source: public/majors.csv, public/schools.csv, public/countries.csv

${entries.join('\n\n')}
`;

writeFileSync(
    path.join(process.cwd(), 'src', 'lib', 'data', 'csvFiles.ts'),
    output
);

console.log('Wrote src/lib/data/csvFiles.ts');
